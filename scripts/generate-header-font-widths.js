// Generates src/features/today/headerFontWidths.ts from the bundled fonts, so
// that the Today header can compute its text widths without a layout pass.
// Run `npm run header-fonts:generate` after a font update.
const fs = require('node:fs');
const path = require('node:path');
const prettier = require('prettier');

const ROOT = path.dirname(require.resolve('../package.json'));
const OUTPUT = path.join(ROOT, 'src/features/today/headerFontWidths.ts');
const FONTS_DIR = path.join(ROOT, 'node_modules/@expo-google-fonts');

let ascii = '';
for (let code = 0x20; code <= 0x7e; code += 1) ascii += String.fromCharCode(code);

const FONTS = [
  {
    name: 'INSTRUMENT_SANS_ADVANCES',
    label: 'Instrument Sans Regular (weather lines)',
    file: 'instrument-sans/400Regular/InstrumentSans_400Regular.ttf',
    characters: `${ascii}àâäæçéèêëîïôöœùûüÿÀÂÄÆÇÉÈÊËÎÏÔÖŒÙÛÜŸ’«»…−°→  `,
  },
  {
    name: 'SPACE_GROTESK_ADVANCES',
    label: 'Space Grotesk Medium (temperatures)',
    file: 'space-grotesk/500Medium/SpaceGrotesk_500Medium.ttf',
    characters: '0123456789−°→  ',
  },
];

function fontReader(file) {
  const font = fs.readFileSync(path.join(FONTS_DIR, file));
  const tables = {};
  for (let index = 0; index < font.readUInt16BE(4); index += 1) {
    const entry = 12 + index * 16;
    tables[font.toString('latin1', entry, entry + 4)] = font.readUInt32BE(entry + 8);
  }
  const unitsPerEm = font.readUInt16BE(tables.head + 18);
  const metricCount = font.readUInt16BE(tables.hhea + 34);

  let cmap = -1;
  for (let index = 0; index < font.readUInt16BE(tables.cmap + 2); index += 1) {
    const offset = tables.cmap + font.readUInt32BE(tables.cmap + 8 + index * 8);
    if (font.readUInt16BE(offset) === 4) cmap = offset;
  }
  if (cmap < 0) throw new Error(`${file}: no format 4 character map`);
  const segments = font.readUInt16BE(cmap + 6) / 2;
  const ends = cmap + 14;
  const starts = ends + segments * 2 + 2;
  const deltas = starts + segments * 2;
  const ranges = deltas + segments * 2;

  function glyphOf(code) {
    for (let index = 0; index < segments; index += 1) {
      if (code > font.readUInt16BE(ends + index * 2)) continue;
      const start = font.readUInt16BE(starts + index * 2);
      if (code < start) return 0;
      const delta = font.readUInt16BE(deltas + index * 2);
      const rangeAt = ranges + index * 2;
      const range = font.readUInt16BE(rangeAt);
      if (range === 0) return (code + delta) & 0xffff;
      const glyph = font.readUInt16BE(rangeAt + range + (code - start) * 2);
      return glyph === 0 ? 0 : (glyph + delta) & 0xffff;
    }
    return 0;
  }

  return function advance(character) {
    const glyph = glyphOf(character.codePointAt(0));
    if (glyph === 0) return null;
    const metric = Math.min(glyph, metricCount - 1);
    return Math.round((font.readUInt16BE(tables.hmtx + metric * 4) / unitsPerEm) * 1000) / 1000;
  };
}

function table({ name, label, file, characters }) {
  const advance = fontReader(file);
  const rows = [...characters].flatMap((character) => {
    const width = advance(character);
    return width === null ? [] : [`  ${JSON.stringify(character)}: ${width},`];
  });
  return `// ${label}.\nexport const ${name}: Readonly<Record<string, number>> = {\n${rows.join('\n')}\n};\n`;
}

async function render() {
  const source = `// Generated by scripts/generate-header-font-widths.js. Do not edit.
// Advance width of each character, as a share of the font size.

${FONTS.map(table).join('\n')}`;
  const options = await prettier.resolveConfig(OUTPUT);
  return prettier.format(source, { ...options, filepath: OUTPUT });
}

if (require.main === module) {
  render().then((text) => fs.writeFileSync(OUTPUT, text));
}

module.exports = { OUTPUT, render };
