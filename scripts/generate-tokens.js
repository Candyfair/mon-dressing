// Generates src/ui/tokens.ts from design/design-system/tokens.json, the source
// of truth for design tokens (CLAUDE.md §5). Run `npm run tokens:generate`
// after any change to tokens.json; a test fails if the committed file drifts.
const fs = require('node:fs');
const path = require('node:path');
const prettier = require('prettier');

const ROOT = path.dirname(require.resolve('../package.json'));
const SOURCE = path.join(ROOT, 'design/design-system/tokens.json');
const OUTPUT = path.join(ROOT, 'src/ui/tokens.ts');

const REFERENCE = /^\{([^}]+)\}$/;

function camelCase(name) {
  return name.replace(/-([a-z0-9])/g, (_match, char) => char.toUpperCase());
}

// "44px" → 44. Only px is used by tokens.json.
function points(value) {
  const match = /^(-?[\d.]+)px$/.exec(value);
  if (!match) {
    throw new Error(`Expected a px value, got ${JSON.stringify(value)}`);
  }
  return Number(match[1]);
}

function round(value) {
  return Math.round(value * 100) / 100;
}

// Value of a themed or theme-independent token for one theme.
function valueFor(token, theme) {
  return typeof token.value === 'string' ? token.value : token.value[theme];
}

// Resolves `{name}` references recursively, within the same theme.
function resolveColors(tokens, theme) {
  const byName = new Map(tokens.map((token) => [token.name, token]));
  const resolve = (name, chain) => {
    if (chain.includes(name)) {
      throw new Error(`Circular token reference: ${[...chain, name].join(' → ')}`);
    }
    const token = byName.get(name);
    if (!token) {
      throw new Error(`Unknown token reference: {${name}} in ${chain.at(-1)}`);
    }
    const value = valueFor(token, theme);
    if (value === undefined) {
      throw new Error(`Token ${name} has no value for theme ${theme}`);
    }
    const reference = REFERENCE.exec(value);
    return reference ? resolve(reference[1], [...chain, name]) : value;
  };
  return Object.fromEntries(
    tokens.map((token) => [camelCase(token.name), resolve(token.name, [])]),
  );
}

function pointsGroup(group) {
  return Object.fromEntries(
    group.tokens.map((token) => [camelCase(token.name), points(token.value)]),
  );
}

// CSS font-family list → the embedded family, its first entry.
function familyName(cssFamilies) {
  return cssFamilies.split(',')[0].trim().replace(/^"|"$/g, '');
}

function typography(type) {
  const families = Object.fromEntries(
    Object.entries(type.families).map(([key, css]) => [key, familyName(css)]),
  );
  const styles = type.groups.flatMap((group) =>
    group.styles.map((style) => {
      const fontSize = points(style.fontSize);
      const lineHeight =
        typeof style.lineHeight === 'number'
          ? style.lineHeight * fontSize
          : points(style.lineHeight);
      const letterSpacing = style.letterSpacing
        ? Number(/^(-?[\d.]+)em$/.exec(style.letterSpacing)[1]) * fontSize
        : undefined;
      return [
        camelCase(style.name),
        {
          fontFamily: families[group.family],
          fontSize,
          lineHeight: round(lineHeight),
          fontWeight: String(style.fontWeight),
          ...(letterSpacing === undefined ? {} : { letterSpacing: round(letterSpacing) }),
        },
      ];
    }),
  );
  return { fontFamilies: families, typography: Object.fromEntries(styles) };
}

function buildTokens(source) {
  const themeIds = source.color.themes.map((theme) => theme.id);
  const themes = Object.fromEntries(
    themeIds.map((theme) => [
      theme,
      {
        colors: resolveColors(source.color.tokens, theme),
        // CSS box-shadow strings, read as is by the `boxShadow` style prop.
        shadows: Object.fromEntries(
          source.shadow.tokens.map((token) => [camelCase(token.name), valueFor(token, theme)]),
        ),
      },
    ]),
  );
  return {
    themes,
    spacing: pointsGroup(source.spacing),
    radius: pointsGroup(source.radius),
    size: pointsGroup(source.size),
    blur: pointsGroup(source.blur),
    opacity: Object.fromEntries(
      source.opacity.tokens.map((token) => [camelCase(token.name), Number(token.value)]),
    ),
    ...typography(source.type),
  };
}

// Formatted with the repo's Prettier config, so lint-staged leaves it untouched.
async function render(source) {
  const tokens = buildTokens(source);
  const exports = Object.entries(tokens).map(
    ([name, value]) => `export const ${name} = ${JSON.stringify(value, null, 2)} as const;\n`,
  );
  const text = [
    `// Generated by scripts/generate-tokens.js from design/design-system/tokens.json`,
    `// (version ${source.version}). Do not edit: run \`npm run tokens:generate\`.`,
    '',
    exports.join('\n'),
    'export type ThemeName = keyof typeof themes;',
    '',
  ].join('\n');
  const options = await prettier.resolveConfig(OUTPUT);
  return prettier.format(text, { ...options, filepath: OUTPUT });
}

function readSource() {
  return JSON.parse(fs.readFileSync(SOURCE, 'utf8'));
}

module.exports = { buildTokens, render, readSource, OUTPUT };

if (require.main === module) {
  render(readSource()).then((text) => {
    fs.writeFileSync(OUTPUT, text);
    console.log(`Wrote ${path.relative(ROOT, OUTPUT)}`);
  });
}
